export function getDiscountPercent(originalPrice, price) {
  if (!originalPrice || !price || price >= originalPrice) return null;
  return Math.round(((originalPrice - price) / originalPrice) * 100);
}

export function isProductAvailable(product) {
  return product.status === 'in_stock' && (!product.sizes?.length || product.sizes.some((size) => size.available));
}

export function productMatchesAudience(product, audience) {
  if (!audience) return true;
  if (audience === 'women') return product.audience === 'women' || product.audience === 'unisex';
  if (audience === 'men') return product.audience === 'men' || product.audience === 'unisex';
  return product.audience === audience;
}

export function getProductBySlug(slug) {
  return products.find((product) => product.slug === slug);
}
